#!/usr/bin/env python3
"""48 MiB file from a synthetic ISO -> anonymous FAT32, independent SHA readback.

Directly patches the synthetic ISO9660 primary tree generated by the
existing MIT fixture tool; contains NO proprietary Windows installer bytes.
"""
from pathlib import Path
import hashlib
import json
import math
import shutil
import struct
import subprocess
import sys
import tempfile

import windows_iso_virtual_fat32_stream as stream

MIB=1024*1024
SECTOR=2048
LBA=128
BYTES=48*MIB
agent=Path("agent/target/debug/bootnexa-media").resolve()
assert agent.is_file(),"native media binary required before synthetic transfer test"
decoder=shutil.which("7z")
assert decoder,"7zip required before synthetic transfer test"

def both32(value):
    return struct.pack("<I",value)+struct.pack(">I",value)

def record(name,start,size):
    encoded=name.encode("ascii")
    rec=bytearray(33+len(encoded)+(len(encoded)%2==0))
    rec[0]=len(rec)
    rec[2:10]=both32(start)
    rec[10:18]=both32(size)
    rec[28:30]=struct.pack("<H",1)
    rec[30:32]=struct.pack(">H",1)
    rec[32]=len(encoded)
    rec[33:33+len(encoded)]=encoded
    return rec

with tempfile.TemporaryDirectory(prefix="bootnexa-large-synthetic-iso-") as folder:
    root=Path(folder)
    efi=root/"TEST.EFI"
    pe=bytearray(512)
    pe[:2]=b"MZ"
    pe[0x3c:0x40]=(0x80).to_bytes(4,"little")
    pe[0x80:0x84]=b"PE\x00\x00"
    pe[0x84:0x86]=bytes([0x64,0x86])
    pe[0x98:0x9a]=bytes([0x0b,0x02])
    pe[0xdc:0xde]=(10).to_bytes(2,"little")
    efi.write_bytes(pe)
    iso=root/"synthetic-medium.iso"
    subprocess.run([sys.executable,"tests/virtual-media/create-iso-fixture.py",
                    str(efi),str(iso),"--profile","windows-preflight"],
                   check=True)
    # Source directory at sector 26. Append an additional real ISO9660
    # file record without rewriting/loosening the original test builder.
    with iso.open("r+b") as target:
        target.seek(26*SECTOR)
        buf=bytearray(target.read(SECTOR))
        pos=0
        while pos<len(buf) and buf[pos]:
            pos+=buf[pos]
        extra=record("LARGE.DAT;1",LBA,BYTES)
        assert pos+len(extra)<=SECTOR
        buf[pos:pos+len(extra)]=extra
        target.seek(26*SECTOR)
        target.write(buf)
        sectors=LBA+math.ceil(BYTES/SECTOR)
        target.seek(16*SECTOR+80)
        target.write(both32(sectors))
        # Deliberately non-zero, patterned bytes for independent SHA proof.
        target.seek(LBA*SECTOR)
        block=bytes(range(256))*256
        assert len(block)==65536
        for _ in range(BYTES//len(block)):
            target.write(block)
    before=stream.source_gate.file_sha(iso,stream.source_gate.MAX_ISO)
    reference={"referenceSha256":before[1],
               "issuer":"synthetic fixture, not Microsoft",
               "locale":"untrusted CI-only"}
    folder_before={p.name for p in root.iterdir()}
    result=stream.stage_verified_stream(
        iso,reference,1,minimum=1,exe=decoder,agent=agent)
    assert result["anonymousStorageAdmissionPassed"]
    assert result["requiredFreeHostBytesAtAdmission"]>=512*MIB
    assert result["stagedBytes"]>=BYTES
    assert result["stagedFileCount"]>=6
    assert result["sourceIsoUnchangedVerified"] is True
    assert not result["persistentDiskImageProduced"]
    assert not result["windowsSetupBootVerified"]
    assert not result["physicalWriteAuthorized"]
    assert not result["fullSizeWindowsInstallerSupported"]
    assert not result["publisherReferenceObtainedLiveForThisRun"]
    all_files={entry["path"]:entry for entry in result["fat32ReadbackFiles"]}
    extra=all_files["SOURCES/LARGE.DAT"]
    assert extra["bytes"]==BYTES
    assert extra["independentFat32ReadbackVerified"] is True
    assert extra["sha256"]==hashlib.sha256(block*(BYTES//len(block))).hexdigest()
    assert stream.source_gate.file_sha(iso,stream.source_gate.MAX_ISO)==before
    assert {p.name for p in root.iterdir()}==folder_before
    print("PASS 48 MiB real ISO9660 file from synthetic optical image into anonymous GPT/FAT32")
    print("PASS independent FAT32 SHA-256 readback, protected source, free-space admission and no output disk")
print("PASS virtual-only enlarged streaming budget does not claim genuine Windows Setup boot")
